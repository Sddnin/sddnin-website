'use strict';

const State = {
  _data: null,
  _listeners: {},

  init() {
    this._data = Storage.load();
    this._checkDailyReset();
    this._checkStreak();
  },

  get(path) {
    if (!path) return this._data;
    return path.split('.').reduce((o, k) => (o && o[k] !== undefined) ? o[k] : undefined, this._data);
  },

  set(path, value) {
    const keys = path.split('.');
    let cur = this._data;
    for (let i = 0; i < keys.length - 1; i++) {
      if (typeof cur[keys[i]] !== 'object' || cur[keys[i]] === null) cur[keys[i]] = {};
      cur = cur[keys[i]];
    }
    cur[keys[keys.length - 1]] = value;
    Storage.save(this._data);
    this._notify(path, value);
  },

  on(path, callback) {
    if (!this._listeners[path]) this._listeners[path] = [];
    this._listeners[path].push(callback);
    return () => {
      this._listeners[path] = this._listeners[path].filter(cb => cb !== callback);
    };
  },

  _notify(path, value) {
    if (this._listeners[path]) {
      this._listeners[path].forEach(cb => cb(value));
    }
    const parts = path.split('.');
    for (let i = parts.length - 1; i > 0; i--) {
      const parent = parts.slice(0, i).join('.');
      if (this._listeners[parent]) {
        this._listeners[parent].forEach(cb => cb(this.get(parent)));
      }
    }
  },

  _checkDailyReset() {
    const today = this._today();
    const goal = this._data.progress.dailyGoal;
    let changed = false;
    Object.keys(goal).forEach(key => {
      if (goal[key].date !== today) {
        goal[key].completed = 0;
        goal[key].date = today;
        changed = true;
      }
    });
    if (changed) Storage.save(this._data);
  },

  _checkStreak() {
    const today = this._today();
    const last = this._data.progress.lastActivityDate;
    if (last) {
      const diff = this._daysBetween(last, today);
      if (diff > 1) {
        this._data.progress.streak = 0;
        Storage.save(this._data);
      }
    }
  },

  addXP(amount, category) {
    this._data.progress.xp += amount;
    const newLevel = this._calcLevel(this._data.progress.xp);
    const leveledUp = newLevel > this._data.progress.level;
    this._data.progress.level = newLevel;

    if (category && this._data.progress.dailyGoal[category]) {
      const g = this._data.progress.dailyGoal[category];
      g.completed += 1;
      g.date = this._today();
    }

    this._touchStreak();
    Storage.save(this._data);
    this._notify('progress', this._data.progress);

    return { leveledUp, newLevel, totalXP: this._data.progress.xp };
  },

  _touchStreak() {
    const today = this._today();
    const last = this._data.progress.lastActivityDate;
    if (last === today) return;

    if (last) {
      const diff = this._daysBetween(last, today);
      if (diff === 1) {
        this._data.progress.streak += 1;
      } else if (diff > 1) {
        this._data.progress.streak = 1;
      }
    } else {
      this._data.progress.streak = 1;
    }

    if (this._data.progress.streak > this._data.progress.longestStreak) {
      this._data.progress.longestStreak = this._data.progress.streak;
    }
    this._data.progress.lastActivityDate = today;
  },

  _calcLevel(xp) {
    for (let i = LEVEL_THRESHOLDS.length - 1; i >= 0; i--) {
      if (xp >= LEVEL_THRESHOLDS[i]) return i + 1;
    }
    return 1;
  },

  getLevelProgress() {
    const { xp, level } = this._data.progress;
    if (level >= LEVEL_THRESHOLDS.length) return 100;
    const cur = LEVEL_THRESHOLDS[level - 1];
    const next = LEVEL_THRESHOLDS[level];
    return Math.floor(((xp - cur) / (next - cur)) * 100);
  },

  getXPForNextLevel() {
    const { level, xp } = this._data.progress;
    if (level >= LEVEL_THRESHOLDS.length) return 0;
    return LEVEL_THRESHOLDS[level] - xp;
  },

  getDailyGoalProgress() {
    const goal = this._data.progress.dailyGoal;
    const today = this._today();
    let totalTarget = 0, totalDone = 0;
    Object.values(goal).forEach(g => {
      if (g.date === today || !g.date) {
        totalTarget += g.target;
        totalDone += Math.min(g.completed, g.target);
      }
    });
    return totalTarget > 0 ? Math.floor((totalDone / totalTarget) * 100) : 0;
  },

  recordActivity(category) {
    this.addXP(XP_VALUES[category] || 5, category);
  },

  _today() {
    return new Date().toISOString().split('T')[0];
  },

  _daysBetween(d1, d2) {
    return Math.floor((new Date(d2) - new Date(d1)) / 86400000);
  }
};